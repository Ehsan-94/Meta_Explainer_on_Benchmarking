    def open_unique_output(self, path):
        stem, extension = os.path.splitext(path)
        repeat = 1
        while True:
            candidate = (path if repeat == 1 else f"{stem}_repeat{repeat:02d}{extension}")
            try:
                return candidate, open(candidate, "xb")
            except FileExistsError:
                repeat += 1
