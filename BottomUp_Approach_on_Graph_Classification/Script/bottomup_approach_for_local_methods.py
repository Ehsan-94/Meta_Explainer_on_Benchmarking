class unify_explanation_to_edge_based:
    def __init__(self, style):
        self.style = style

        if self.style not in ["Node", "Edge"]:
            raise ValueError("style must be either 'Node' or 'Edge'.")

    def __call__(self, explanation, graph):

        if self.style == "Edge":
            if len(explanation) != graph.edge_index.size(1):
                raise ValueError(f"Edge explanation length ({len(explanation)}) does not match "
                                 f"number of graph edges ({graph.edge_index.size(1)}).")
            return explanation

        elif self.style == "Node":
            if len(explanation) != graph.num_nodes:
                raise ValueError(f"Node explanation length ({len(explanation)}) does not match "
                                 f"number of graph nodes ({graph.num_nodes}).")
            edge_explanation = []
            for source_index, target_index in graph.edge_index.T.tolist():
                if (explanation[source_index] == 1 and explanation[target_index] == 1):
                    edge_explanation.append(1)
                else:
                    edge_explanation.append(0)

            return edge_explanation


class profile_frequencies_by_edge_based_explanations:
    def __init__(self, list_of_saliencies, test_dataset):
        self.list_of_saliencies = list_of_saliencies
        self.edges_profile_by_node_feats = {}
        self.edges_profile_by_node_feats_2_proportions = {}
        self.test_dataset = test_dataset

        if len(self.list_of_saliencies) != len(self.test_dataset):
            raise ValueError("Number of explanations must match number of test graphs.")

        self.is_one_hot = self.check_if_node_features_are_one_hot()
        self.has_tokens = all(hasattr(graph, "tokens") for graph in self.test_dataset)

        if not self.is_one_hot and not self.has_tokens:
            raise ValueError("Bottom-Up adaptation requires either one-hot node features or discrete node tokens.")

        if self.has_tokens:
            for graph in self.test_dataset:
                if len(graph.tokens) != graph.num_nodes:
                    raise ValueError("Number of node tokens does not match number of graph nodes.")

        self.profile_edges_for_each_explanation()
        self.get_proportions()

    def check_if_node_features_are_one_hot(self):
        for graph in self.test_dataset:
            node_feats = graph.x

            if not torch.all((node_feats == 0) | (node_feats == 1)):
                return False

            if not torch.all(node_feats.sum(dim=1) == 1):
                return False

        return True

    def get_node_key(self, graph, node_index):
        if hasattr(graph, "tokens"):
            return graph.tokens[node_index]

        return tuple(graph.x[node_index].tolist())

    def profile_edges_for_each_explanation(self):
        for expl, graph in zip(self.list_of_saliencies, self.test_dataset):
            graph_edges = graph.edge_index.T.tolist()

            if len(expl) != len(graph_edges):
                raise ValueError(f"Edge explanation length ({len(expl)}) does not match "
                                 f"number of graph edges ({len(graph_edges)}).")

            for edge_sal, (source_index, target_index) in zip(expl, graph_edges):
                if edge_sal == 1:
                    edge_key = (self.get_node_key(graph, source_index), self.get_node_key(graph, target_index))

                    if edge_key in self.edges_profile_by_node_feats:
                        self.edges_profile_by_node_feats[edge_key] += 1
                    else:
                        self.edges_profile_by_node_feats[edge_key] = 1

    def get_proportions(self):
        sum_value = sum(self.edges_profile_by_node_feats.values())

        if sum_value == 0:
            print("Bottom-Up profile is empty: "
                  "no salient edge patterns were found.")
            return

        for key, value in self.edges_profile_by_node_feats.items():
            self.edges_profile_by_node_feats_2_proportions[key] = (value / sum_value)

    def profile_the_upcoming_explanation(self, an_explanation, a_graph):
        graph_edges = a_graph.edge_index.T.tolist()

        if len(an_explanation) != len(graph_edges):
            raise ValueError(f"Edge explanation length ({len(an_explanation)}) does not match "
                             f"number of graph edges ({len(graph_edges)}).")

        profile = []

        for sal_score, (source_index, target_index) in zip(an_explanation, graph_edges):
            edge_key = (self.get_node_key(a_graph, source_index), self.get_node_key(a_graph, target_index))

            if sal_score == 1:
                profile.append(self.edges_profile_by_node_feats_2_proportions.get(edge_key, 0))
            else:
                profile.append(0)
        return profile

    def __call__(self, an_explanation, a_graph, threshold):
        profile = self.profile_the_upcoming_explanation(an_explanation, a_graph)

        profile_one_hot = [1 if value > threshold else 0 for value in profile]

        if len(profile_one_hot) != a_graph.edge_index.size(1):
            raise ValueError(f"Adapted explanation length ({len(profile_one_hot)}) does not match "
                             f"number of graph edges ({a_graph.edge_index.size(1)}).")

        return profile_one_hot




























