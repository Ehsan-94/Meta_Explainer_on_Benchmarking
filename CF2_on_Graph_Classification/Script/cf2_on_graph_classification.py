class CF2_Manager:
    def __init__(self, GNN_Model, dataset_name, num_classes, explainer_epochs, input_dim, hid_dim, output_dim,
                 save_root):
        self.device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
        self.GNN_Model = GNN_Model.to(self.device)
        self.dataset_name = dataset_name
        self.num_classes = num_classes
        self.explainer_epochs = explainer_epochs
        self.input_dim = input_dim
        self.hid_dim = hid_dim
        self.output_dim = output_dim
        self.save_root = save_root
        self.Model_Name = self.GNN_Model.__class__.__name__
        self.save_dir = os.path.join(self.save_root, "CF2_on_Graph_Classification", "Experimental_Results")
        os.makedirs(self.save_dir, exist_ok=True)
        self.save_path = os.path.join(self.save_dir, f"{self.dataset_name}_"f"{self.Model_Name}_"f"CF2.pt")

    def generate_explanations(self, test_dataset, binarization_threshold):
        edge_explanations = {class_index: [] for class_index in range(self.num_classes)}
        binary_edge_explanations = {class_index: [] for class_index in range(self.num_classes)}
        total_runtime = 0.0
        runtime_per_class = {}
        for class_index in range(self.num_classes):
            cf2_explanation = CF2_Explaination(GNN_Model=self.GNN_Model, your_dataset=test_dataset,
                                               explainer_epochs=self.explainer_epochs, fix_exp=None,
                                               input_dim=self.input_dim, hid_dim=self.hid_dim,
                                               output_dim=self.output_dim)
            class_t1 = perf_counter()
            exp_dict = cf2_explanation.explain_nodes_gnn_stats(category=class_index)
            class_runtime = (perf_counter() - class_t1)
            runtime_per_class[class_index] = class_runtime
            total_runtime += class_runtime
            for graph_index in range(len(test_dataset)):
                edge_mask = exp_dict[graph_index]
                edge_mask_cpu = (edge_mask.detach().cpu() if torch.is_tensor(edge_mask)
                                 else torch.tensor(edge_mask, dtype=torch.float32))
                edge_explanations[class_index].append(edge_mask_cpu)
                binary_edge_mask = (edge_mask_cpu >= binarization_threshold).int()
                binary_edge_explanations[class_index].append(binary_edge_mask)
        average_explanation_runtime_per_graph_class = (total_runtime / (len(test_dataset) * self.num_classes))
        average_explanation_runtime_all_classes_per_graph = (total_runtime / len(test_dataset))
        saved_data = {
            "explainer": "CF2",
            "dataset": self.dataset_name,
            "gnn": self.Model_Name,
            "num_classes": self.num_classes,
            "edge_explanations": edge_explanations,
            "binary_edge_explanations": binary_edge_explanations,
            "binarization_threshold": binarization_threshold,
            "graph_indices": list(range(len(test_dataset))),
            "graph_labels": [int(graph.y.item()) for graph in test_dataset],
            "num_nodes": [int(graph.num_nodes) for graph in test_dataset],
            "num_edges": [int(graph.edge_index.size(1)) for graph in test_dataset],
            "explainer_epoch": self.explainer_epochs,
            "total_runtime": total_runtime,
            "runtime_per_class": runtime_per_class,
            "average_explanation_runtime_per_graph_class": average_explanation_runtime_per_graph_class,
            "average_explanation_runtime_all_classes_per_graph": average_explanation_runtime_all_classes_per_graph,}
        torch.save(saved_data, self.save_path)
        print("CF2 explanations saved to:", self.save_path)

        return saved_data

    def load_explanations(self):
        return torch.load(self.save_path, map_location="cpu")

    def __call__(self, CF2_Mode, test_dataset=None, binarization_threshold=0.5):
        if CF2_Mode == "generate":
            if test_dataset is None:
                raise ValueError("test_dataset is required for CF2_Mode='generate'.")
            return self.generate_explanations(test_dataset=test_dataset, binarization_threshold=binarization_threshold)
        elif CF2_Mode == "load":
            return self.load_explanations()
        else:
            raise ValueError("CF2_Mode must be 'generate' or 'load'.")