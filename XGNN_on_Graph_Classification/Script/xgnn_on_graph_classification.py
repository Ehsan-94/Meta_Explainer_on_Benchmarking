    def get_node_degree_constraints(self, reference_dataset, candidate_node_types):
        predefined_constraints = {"MUTAG": {0: 4, 1: 5, 2: 2, 3: 1, 4: 7, 5: 7, 6: 5},
                                  "IsCyclic": {0: 10, 1: 10, 2: 10, 3: 10, 4: 10, 5: 10, 6: 10, 7: 10, 8: 10, 9: 10}}
        if self.dataset_name in predefined_constraints:
            return predefined_constraints[self.dataset_name]
        elif self.dataset_name in ["NCI1", "ENZYMES", "PROTEINS"]:
            return self.get_max_degree_per_node_type(reference_dataset=reference_dataset,
                                                     candidate_node_types=candidate_node_types)
        else:
            raise ValueError(f"XGNN does not support dataset '{self.dataset_name}'.")

    def get_candidate_node_types(self, reference_dataset):
        predefined_candidate_node_types = {"MUTAG": list(range(7)), "IsCyclic": list(range(10))}
        if self.dataset_name in predefined_candidate_node_types:
            return predefined_candidate_node_types[self.dataset_name]
        elif self.dataset_name in ["NCI1", "ENZYMES", "PROTEINS"]:
            candidate_node_types = set()
            for graph in reference_dataset:
                node_types = torch.argmax(graph.x, dim=1).tolist()
                candidate_node_types.update(node_types)
            return sorted(candidate_node_types)
        else:
            raise ValueError(f"XGNN does not support dataset '{self.dataset_name}'.")

    def get_max_degree_per_node_type(self, reference_dataset, candidate_node_types):
        max_degree_per_type = {node_type: 0 for node_type in candidate_node_types}
        for graph in reference_dataset:
            degrees = torch.bincount(graph.edge_index[0], minlength=graph.num_nodes)
            for node_index in range(graph.num_nodes):
                node_type = int(torch.argmax(graph.x[node_index]).item())
                node_degree = int(degrees[node_index].item())
                max_degree_per_type[node_type] = max(max_degree_per_type[node_type], node_degree)

        return max_degree_per_type

