class PGExplainer_Manager:
    def __init__(self, GNN_Model, dataset_name, num_classes, Exp_Epoch, Exp_lr, node_feat_dim, save_root):
        self.device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')

        self.GNN_Model = GNN_Model.to(self.device)

        self.dataset_name = dataset_name
        self.num_classes = num_classes

        self.Exp_Epoch = Exp_Epoch
        self.Exp_lr = Exp_lr

        self.node_feat_dim = node_feat_dim
        self.save_root = save_root

        self.Model_Name = self.GNN_Model.__class__.__name__
        self.save_dir = os.path.join(self.save_root, "PGExplainer_on_Graph_Classification", "Experimental_Results")
        os.makedirs(self.save_dir, exist_ok=True)
        self.save_path = os.path.join(self.save_dir, f"{self.dataset_name}_"f"{self.Model_Name}_"f"PGExplainer.pt")
    def train_explainers(self, explainer_training_dataset):
        training_runtime = 0.0
        runtime_per_class = {}
        for class_index in range(self.num_classes):
            explainer = PGExplainer(GNN_Model=self.GNN_Model, explainer_save_index=self.Exp_Epoch,
                                    Exp_Epoch=self.Exp_Epoch, Exp_lr=self.Exp_lr, node_feat_dim=self.node_feat_dim,
                                    dataset_name=self.dataset_name)
            t1 = perf_counter()
            explainer(ExTrain_or_ExTest="train", Exp_Load_index=self.Exp_Epoch, your_dataset=explainer_training_dataset,
                      target_class=class_index)
            class_runtime = perf_counter() - t1
            runtime_per_class[class_index] = class_runtime
            training_runtime += class_runtime
        return {"training_runtime": training_runtime, "training_runtime_per_class": runtime_per_class,
                "average_training_runtime_per_class": training_runtime / self.num_classes}

    def generate_test_explanations(self, test_dataset, binarization_threshold):
        edge_explanations = {class_index: [] for class_index in range(self.num_classes)}
        binary_edge_explanations = {class_index: [] for class_index in range(self.num_classes)}
        testing_runtime = 0.0
        runtime_per_class = {}
        with torch.no_grad():
            for class_index in range(self.num_classes):
                explainer = PGExplainer(GNN_Model=self.GNN_Model, explainer_save_index=self.Exp_Epoch,
                                        Exp_Epoch=self.Exp_Epoch, Exp_lr=self.Exp_lr, node_feat_dim=self.node_feat_dim,
                                        dataset_name=self.dataset_name)
                pgexp_mlp, _ = explainer.load_explainer_mlp(Exp_Load_index=self.Exp_Epoch, target_class=class_index)
                # test_graphs = [copy.deepcopy(graph) for graph in test_dataset]
                class_t1 = perf_counter()
                _, returned_masks = explainer.test_explainer(self.GNN_Model, test_dataset, pgexp_mlp)
                class_runtime = perf_counter() - class_t1
                testing_runtime += class_runtime
                runtime_per_class[class_index] = class_runtime
                for edge_mask in returned_masks:
                    edge_mask_cpu = (edge_mask.detach().cpu()
                                     if torch.is_tensor(edge_mask) else torch.tensor(edge_mask, dtype=torch.float32))
                    edge_explanations[class_index].append(edge_mask_cpu)
                    binary_edge_mask = (edge_mask_cpu >= binarization_threshold).int()
                    binary_edge_explanations[class_index].append(binary_edge_mask)

        average_explanation_runtime_per_graph_class = (testing_runtime / (len(test_dataset) * self.num_classes))
        average_explanation_runtime_all_classes_per_graph = (testing_runtime / len(test_dataset))
        explanation_sizes_per_class = {}
        average_explanation_size_per_class = {}
        for class_index in range(self.num_classes):
            class_sizes = [int(binary_edge_mask.sum().item()) for binary_edge_mask in
                           binary_edge_explanations[class_index]]
            explanation_sizes_per_class[class_index] = class_sizes
            average_explanation_size_per_class[class_index] = (
                sum(class_sizes) / len(class_sizes) if len(class_sizes) > 0 else 0.0)
        saved_data = {
            "explainer": "PGExplainer",
            "dataset": self.dataset_name,
            "gnn": self.Model_Name,
            "num_classes": self.num_classes,
            "edge_explanations": edge_explanations,
            "binary_edge_explanations": binary_edge_explanations,
            "explanation_sizes_per_class": explanation_sizes_per_class,
            "average_explanation_size_per_class": average_explanation_size_per_class,
            "binarization_threshold": binarization_threshold,
            "graph_indices": list(range(len(test_dataset))),
            "graph_labels": [int(graph.y.item()) for graph in test_dataset],
            "num_nodes": [int(graph.num_nodes) for graph in test_dataset],
            "num_edges": [int(graph.edge_index.size(1)) for graph in test_dataset],
            "explainer_epoch": self.Exp_Epoch,
            "explainer_learning_rate": self.Exp_lr,
            "testing_runtime": testing_runtime,
            "runtime_per_class": runtime_per_class,
            "average_explanation_runtime_per_graph_class": average_explanation_runtime_per_graph_class,
            "average_explanation_runtime_all_classes_per_graph": average_explanation_runtime_all_classes_per_graph,}
        torch.save(saved_data, self.save_path)
        print("PGExplainer explanations saved to:", self.save_path)
        return saved_data

    def load_explanations(self):
        return torch.load(self.save_path, map_location="cpu")

    def __call__(self, PGE_Mode, explainer_training_dataset=None, test_dataset=None, binarization_threshold=0.5):
        if PGE_Mode == "train":
            if explainer_training_dataset is None:
                raise ValueError("explainer_training_dataset is required for Mode='train'.")
            return self.train_explainers(explainer_training_dataset)
        elif PGE_Mode == "test":
            if test_dataset is None:
                raise ValueError("test_dataset is required for Mode='test'.")
            return self.generate_test_explanations(test_dataset, binarization_threshold)
        elif PGE_Mode == "load":
            return self.load_explanations()
        else:
            raise ValueError("Mode must be 'train', 'test', or 'load'.")