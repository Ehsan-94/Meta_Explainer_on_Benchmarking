class PGMExplainer_Manager:
    def __init__(self, GNN_Model, dataset_name, num_classes, perturb_feature_list=None, perturb_mode="mean",
                 perturb_indicator="abs", num_samples_rule="num_nodes", noise_offset_percentage=50, top_node=5,
                 p_value_threshold=0.05, save_root=None):
        self.device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')

        self.GNN_Model = GNN_Model.to(self.device)
        self.GNN_Model.eval()

        for param in self.GNN_Model.parameters():
            param.requires_grad_(False)

        self.dataset_name = dataset_name
        self.num_classes = num_classes

        if perturb_feature_list is None:
            perturb_feature_list = [None]

        self.perturb_feature_list = perturb_feature_list
        self.perturb_mode = perturb_mode
        self.perturb_indicator = perturb_indicator

        self.num_samples_rule = num_samples_rule
        self.noise_offset_percentage = noise_offset_percentage
        self.top_node = top_node
        self.p_value_threshold = p_value_threshold

        if save_root is None:
            raise ValueError("save_root must be provided.")

        self.save_root = save_root
        self.Model_Name = self.GNN_Model.__class__.__name__
        self.save_dir = os.path.join(self.save_root, "PGMExplainer_on_Graph_Classification", "Experimental_Results")

        os.makedirs(self.save_dir, exist_ok=True)
        self.save_path = os.path.join(self.save_dir, f"{self.dataset_name}_{self.Model_Name}_PGMExplainer.pt")
    def generate_explanations(self, test_dataset):
        node_explanations = {class_index: [] for class_index in range(self.num_classes)}
        selected_nodes = {class_index: [] for class_index in range(self.num_classes)}
        p_values_all = {class_index: [] for class_index in range(self.num_classes)}
        candidate_nodes_all = {class_index: [] for class_index in range(self.num_classes)}
        dependent_nodes_all = {class_index: [] for class_index in range(self.num_classes)}
        total_runtime = 0.0
        runtime_per_class = {}
        for class_index in range(self.num_classes):
            class_t1 = perf_counter()
            for graph in test_dataset:
                graph_to_explain = copy.deepcopy(graph)
                pgmx = PGM_Graph_Explainer(GNN_Model=self.GNN_Model, graph=graph_to_explain,
                                           perturb_feature_list=self.perturb_feature_list,
                                           perturb_mode=self.perturb_mode, perturb_indicator=self.perturb_indicator)
                if self.num_samples_rule == "num_nodes":
                    num_samples = len(graph_to_explain.x)
                else:
                    raise ValueError(f"Unsupported num_samples_rule: {self.num_samples_rule}")
                pgm_node, p_values, candidate_nodes, dependent_nodes = pgmx.explain(num_samples=num_samples,
                                                                                    noise_offset_percentage=self.noise_offset_percentage,
                                                                                    top_node=self.top_node,
                                                                                    p_value_threshold=self.p_value_threshold,
                                                                                    class_index=class_index)
                binary_node_mask = torch.zeros(len(graph_to_explain.x), dtype=torch.int)
                binary_node_mask[pgm_node] = 1
                node_explanations[class_index].append(binary_node_mask)
                selected_nodes[class_index].append(list(pgm_node))
                p_values_all[class_index].append(list(p_values))
                candidate_nodes_all[class_index].append(
                    candidate_nodes.tolist() if isinstance(candidate_nodes, np.ndarray) else list(candidate_nodes))
                dependent_nodes_all[class_index].append(list(dependent_nodes))

            class_runtime = perf_counter() - class_t1
            runtime_per_class[class_index] = class_runtime
            total_runtime += class_runtime
        average_explanation_runtime_per_graph_class = (total_runtime / (len(test_dataset) * self.num_classes))
        average_explanation_runtime_all_classes_per_graph = (total_runtime / len(test_dataset))
        saved_data = {
            "explainer": "PGMExplainer",
            "dataset": self.dataset_name,
            "gnn": self.Model_Name,
            "num_classes": self.num_classes,
            "node_explanations": node_explanations,
            "selected_nodes": selected_nodes,
            "p_values": p_values_all,
            "candidate_nodes": candidate_nodes_all,
            "dependent_nodes": dependent_nodes_all,
            "graph_indices": list(range(len(test_dataset))),
            "graph_labels": [int(graph.y.item()) for graph in test_dataset],
            "num_nodes": [int(graph.num_nodes) for graph in test_dataset],
            "num_edges": [int(graph.edge_index.size(1)) for graph in test_dataset],
            "num_samples_rule": self.num_samples_rule,
            "noise_offset_percentage": self.noise_offset_percentage,
            "top_node": self.top_node,
            "p_value_threshold": self.p_value_threshold,
            "perturb_feature_list": self.perturb_feature_list,
            "perturb_mode": self.perturb_mode,
            "perturb_indicator": self.perturb_indicator,
            "total_runtime": total_runtime,
            "runtime_per_class": runtime_per_class,
            "average_explanation_runtime_per_graph_class": average_explanation_runtime_per_graph_class,
            "average_explanation_runtime_all_classes_per_graph": average_explanation_runtime_all_classes_per_graph,
        }

        torch.save(saved_data, self.save_path)
        print("PGMExplainer explanations saved to:", self.save_path)
        return saved_data

    def load_explanations(self):
        return torch.load(self.save_path, map_location="cpu")

    def __call__(self, PGM_Mode, test_dataset=None):
        if PGM_Mode == "generate":
            if test_dataset is None:
                raise ValueError("test_dataset is required for PGM_Mode='generate'.")
            return self.generate_explanations(test_dataset=test_dataset)
        elif PGM_Mode == "load":
            return self.load_explanations()
        else:
            raise ValueError("PGM_Mode must be 'generate' or 'load'.")
