class continuous_node_features_to_token_keys:
    def __init__(self, reference_dataset):
        self.reference_dataset = reference_dataset
        self.token_prototypes = self.build_token_prototypes()

    def build_token_prototypes(self):
        token_embeddings = {}
        for graph in self.reference_dataset:
            if not hasattr(graph, "tokens"):
                raise ValueError("Graphs must contain tokens for continuous-feature Top-Down adaptation.")
            if len(graph.tokens) != graph.num_nodes:
                raise ValueError("Number of node tokens does not match number of graph nodes.")
            for node_index, token in enumerate(graph.tokens):
                if token not in token_embeddings:
                    token_embeddings[token] = []
                token_embeddings[token].append(graph.x[node_index].detach().cpu())
        if len(token_embeddings) == 0:
            raise ValueError("No token embeddings were found in the reference dataset.")
        token_prototypes = {}
        for token, embeddings in token_embeddings.items():
            token_prototypes[token] = torch.stack(embeddings, dim=0).mean(dim=0)

        return token_prototypes

    def get_nearest_token(self, node_feature):
        node_feature = node_feature.detach().cpu()
        best_token = None
        best_similarity = -float("inf")
        for token, prototype in self.token_prototypes.items():
            if node_feature.numel() != prototype.numel():
                raise ValueError("Generated node-feature dimension does not match "
                                 "Graph-SST5 token-prototype dimension.")
            similarity = F.cosine_similarity(node_feature.unsqueeze(0), prototype.unsqueeze(0), dim=1).item()
            if similarity > best_similarity:
                best_similarity = similarity
                best_token = token

        return best_token

    def __call__(self, node_features):
        node_keys = []
        for node_feature in node_features:
            node_keys.append(self.get_nearest_token(node_feature))

        return node_keys





class global_explanation_and_samples_intersection:
    def __init__(self, explanation, input_graph, explanation_node_keys=None, input_graph_node_keys=None):
        self.explanation = explanation
        self.input_graph = input_graph

        self.explanation_node_keys = explanation_node_keys
        self.input_graph_node_keys = input_graph_node_keys

    def pair_source_and_target_node_features(self, edges, node_keys):
        paired_feat = {}
        for source_index, target_index in edges:
            edge_key = (node_keys[source_index], node_keys[target_index])
            paired_feat[(source_index, target_index)] = edge_key
        return paired_feat

    def find_common_edges(self, ex_graph_node_keys, ex_graph_edge_index, input_graph_node_keys, input_graph_edge_index):

        ex_graph_edges = [(source_index, target_index) for source_index, target_index in ex_graph_edge_index.T.tolist()]

        input_graph_edges = [(source_index, target_index) for source_index, target_index in
                             input_graph_edge_index.T.tolist()]

        ex_graph_paired_node_features = (self.pair_source_and_target_node_features(ex_graph_edges, ex_graph_node_keys))
        input_graph_paired_node_features = (
            self.pair_source_and_target_node_features(input_graph_edges, input_graph_node_keys))
        common_edges = {}
        for (inp_graph_source_index,
             inp_graph_target_index), inp_graph_paired_feat in input_graph_paired_node_features.items():
            presence = 0
            for ex_graph_paired_feat in (ex_graph_paired_node_features.values()):
                if inp_graph_paired_feat == ex_graph_paired_feat:
                    presence = 1
                    break
            common_edges[(inp_graph_source_index, inp_graph_target_index)] = presence

        return common_edges

    def __call__(self):
        if self.explanation_node_keys is None:
            explanation_node_keys = [tuple(node_feat) for node_feat in self.explanation.x.tolist()]
        else:
            explanation_node_keys = self.explanation_node_keys

        if self.input_graph_node_keys is None:
            input_graph_node_keys = [tuple(node_feat) for node_feat in self.input_graph.x.tolist()]
        else:
            input_graph_node_keys = self.input_graph_node_keys

        if len(explanation_node_keys) != self.explanation.num_nodes:
            raise ValueError("Number of explanation node keys does not match number of explanation nodes.")
        if len(input_graph_node_keys) != self.input_graph.num_nodes:
            raise ValueError("Number of input-graph node keys does not match number of input-graph nodes.")

        return self.find_common_edges(explanation_node_keys, self.explanation.edge_index, input_graph_node_keys,
                                      self.input_graph.edge_index)


