class FidelityPlus:
    """
    Fidelity+ for graph-classification explanations.

    Expected format:
        explanations[class_index][graph_index] -> explanation tensor/array

    explanation_style:
        "Node", "Edge", "Node Feature"

    drop_style:
        "zeroing" or "deleting"

    fidelity_criterion:
        "probability", "prediction", "accuracy", "auc_roc"

    The project's four GNN models already return softmax probabilities as
    their final model_prediction, so no additional softmax is applied here.
    """

    def __init__(self, GNN_Model, test_data, device, explanation_style="Node", explanation_type="binary",
                 normalization="none", importance_threshold=None, drop_style="deleting",
                 fidelity_criterion="probability", class_scope="all_classes", class_aggregation="macro",
                 edge_semantics=None, ):
        self.GNN_Model = GNN_Model
        self.test_data = test_data
        self.device = device
        self.explanation_style = explanation_style
        self.explanation_type = explanation_type
        self.normalization = normalization
        self.importance_threshold = importance_threshold
        self.drop_style = drop_style
        self.fidelity_criterion = fidelity_criterion
        self.class_scope = class_scope
        self.class_aggregation = class_aggregation
        self.edge_semantics = edge_semantics
        self._validate_configuration()

    def _validate_configuration(self):
        if self.explanation_style not in ("Node", "Edge", "Node Feature"):
            raise ValueError("explanation_style must be 'Node', 'Edge', or 'Node Feature'.")
        if self.explanation_type not in ("binary", "continuous"):
            raise ValueError("explanation_type must be 'binary' or 'continuous'.")
        if self.normalization not in ("none", "minmax"):
            raise ValueError("normalization must be 'none' or 'minmax'.")
        if self.drop_style not in ("zeroing", "deleting"):
            raise ValueError("drop_style must be 'zeroing' or 'deleting'.")
        if self.fidelity_criterion not in ("probability", "prediction", "accuracy", "auc_roc"):
            raise ValueError("Invalid fidelity_criterion.")
        if self.class_scope not in ("all_classes", "ground-truth label", "prediction"):
            raise ValueError("Invalid class_scope.")
        if self.class_aggregation not in ("macro", "class_frequency_weighted"):
            raise ValueError("Invalid class_aggregation.")

        if self.explanation_style == "Edge":
            if self.edge_semantics not in ("directed", "undirected"):
                raise ValueError("Edge explanations require directed/undirected edge_semantics.")
        elif self.edge_semantics is not None:
            raise ValueError("edge_semantics should be None for non-edge explanations.")

        if self.explanation_type == "binary":
            if self.normalization != "none":
                raise ValueError("Binary explanations should use normalization='none'.")
            if self.importance_threshold is not None:
                raise ValueError("Binary explanations do not require importance_threshold.")
        elif self.importance_threshold is None:
            raise ValueError("Continuous explanations require importance_threshold.")

        if self.explanation_style == "Node Feature" and self.drop_style == "deleting":
            raise ValueError("Node Feature explanations support zeroing, not deleting.")

    @staticmethod
    def _minmax_normalize(scores):
        scores = scores.float()
        if scores.numel() == 0:
            return scores
        lo, hi = scores.min(), scores.max()
        if torch.isclose(hi, lo):
            return torch.zeros_like(scores)
        return (scores - lo) / (hi - lo)

    def _important_mask(self, explanation):
        scores = torch.as_tensor(explanation)
        if self.explanation_type == "binary":
            return scores.bool()
        scores = scores.float()
        if self.normalization == "minmax":
            scores = self._minmax_normalize(scores)
        return scores >= self.importance_threshold

    def _model_prediction(self, graph, edge_mask=None):
        graph = copy.deepcopy(graph).to(self.device)
        if edge_mask is not None:
            edge_mask = edge_mask.to(self.device)

        name = self.GNN_Model.__class__.__name__
        with torch.no_grad():
            if name == "GCN_plus_GAP_Model":
                _, _, _, pred = self.GNN_Model(graph, edge_mask)
            elif name == "DGCNN_Model":
                _, _, _, _, _, _, _, _, _, pred = self.GNN_Model(graph, edge_mask)
            elif name == "DIFFPOOL_Model":
                _, _, pred = self.GNN_Model(graph, edge_mask)
            elif name == "GIN_Model":
                _, _, _, _, _, pred = self.GNN_Model(graph, edge_mask)
            else:
                raise ValueError(f"Unsupported GNN model: {name}")

        pred = torch.squeeze(pred)
        return pred.unsqueeze(0) if pred.dim() == 0 else pred

    @staticmethod
    def _undirected_expand_mask(edge_index, selected_mask):
        selected_mask = selected_mask.bool().clone()
        pairs = set()
        for idx in torch.where(selected_mask)[0].tolist():
            u, v = int(edge_index[0, idx]), int(edge_index[1, idx])
            pairs.add((min(u, v), max(u, v)))

        expanded = torch.zeros(edge_index.size(1), dtype=torch.bool, device=edge_index.device)
        for idx in range(edge_index.size(1)):
            u, v = int(edge_index[0, idx]), int(edge_index[1, idx])
            if (min(u, v), max(u, v)) in pairs:
                expanded[idx] = True
        return expanded

    def _prepare_edge_mask(self, graph, mask):
        mask = mask.to(graph.edge_index.device)
        if mask.numel() != graph.edge_index.size(1):
            raise ValueError("Edge explanation length != number of edge_index entries.")
        if self.edge_semantics == "undirected":
            mask = self._undirected_expand_mask(graph.edge_index, mask)
        return mask

    def _zero_nodes(self, graph, mask):
        g = copy.deepcopy(graph)
        mask = mask.to(g.x.device)
        if mask.numel() != g.num_nodes:
            raise ValueError("Node explanation length != graph.num_nodes.")
        g.x[mask] = 0
        return g, None

    def _delete_nodes(self, graph, mask):
        g = copy.deepcopy(graph)
        mask = mask.to(g.x.device)
        if mask.numel() != g.num_nodes:
            raise ValueError("Node explanation length != graph.num_nodes.")
        keep = ~mask
        if keep.sum().item() == 0:
            g.x = torch.empty((0, g.x.size(-1)), dtype=g.x.dtype, device=g.x.device)
            g.edge_index = torch.empty((2, 0), dtype=g.edge_index.dtype, device=g.edge_index.device)
            if getattr(g, "edge_attr", None) is not None:
                ea = g.edge_attr
                g.edge_attr = torch.empty((0,) + tuple(ea.shape[1:]), dtype=ea.dtype, device=ea.device)
            if getattr(g, "batch", None) is not None:
                g.batch = torch.empty((0,), dtype=g.batch.dtype, device=g.batch.device)
            return g, None

        subset = torch.where(keep)[0]
        old_edge_attr = getattr(g, "edge_attr", None)
        new_edge_index, new_edge_attr = subgraph(subset, g.edge_index, old_edge_attr, relabel_nodes=True,
                                                 num_nodes=g.num_nodes)
        g.x = g.x[keep]
        g.edge_index = new_edge_index
        if old_edge_attr is not None:
            g.edge_attr = new_edge_attr
        if getattr(g, "batch", None) is not None:
            g.batch = torch.zeros(g.x.size(0), dtype=g.batch.dtype, device=g.batch.device)
        return g, None

    def _zero_edges(self, graph, mask):
        g = copy.deepcopy(graph)
        mask = self._prepare_edge_mask(g, mask)
        edge_mask = torch.ones(g.edge_index.size(1), dtype=g.x.dtype, device=g.edge_index.device)
        edge_mask[mask] = 0.0
        return g, edge_mask

    def _delete_edges(self, graph, mask):
        g = copy.deepcopy(graph)
        mask = self._prepare_edge_mask(g, mask)
        keep = ~mask
        g.edge_index = g.edge_index[:, keep]
        if getattr(g, "edge_attr", None) is not None:
            g.edge_attr = g.edge_attr[keep]
        return g, None

    def _zero_node_features(self, graph, mask):
        g = copy.deepcopy(graph)
        mask = mask.to(g.x.device)
        if mask.shape != g.x.shape:
            raise ValueError("Node Feature explanation shape must equal graph.x shape.")
        g.x[mask] = 0
        return g, None

    def _perturb_graph(self, graph, explanation):
        mask = self._important_mask(explanation)
        if self.explanation_style == "Node":
            return self._zero_nodes(graph, mask) if self.drop_style == "zeroing" else self._delete_nodes(graph, mask)
        if self.explanation_style == "Edge":
            return self._zero_edges(graph, mask) if self.drop_style == "zeroing" else self._delete_edges(graph, mask)
        return self._zero_node_features(graph, mask)

    def _original_predictions(self):
        return [self._model_prediction(g).detach().cpu() for g in self.test_data]

    def _classes_for_graph(self, graph_index, original, explanations):
        if self.class_scope == "all_classes":
            return sorted(explanations.keys())
        if self.class_scope == "ground-truth label":
            return [int(self.test_data[graph_index].y.item())]
        return [int(torch.argmax(original[graph_index]).item())]

    def _aggregate_classes(self, scores):
        valid = {c: v for c, v in scores.items() if v}
        if not valid:
            raise ValueError("No valid Fidelity+ scores.")
        means = {c: float(np.mean(v)) for c, v in valid.items()}

        if self.class_aggregation == "macro":
            return float(np.mean(list(means.values()))), means

        labels = [int(g.y.item()) for g in self.test_data]
        weights = {c: labels.count(c) / len(labels) for c in means}
        total = sum(weights.values())
        weights = {c: w / total for c, w in weights.items()}
        final = sum(weights[c] * means[c] for c in means)
        return float(final), means

    def _predict_perturbed(self, graph, edge_mask, graph_index, class_index=None):
        try:
            return self._model_prediction(graph, edge_mask)
        except Exception as exc:
            if self.drop_style == "deleting" and graph.num_nodes == 0:
                suffix = (f", class_index={class_index}" if class_index is not None else "")
                raise RuntimeError(
                    "Deletion produced a true empty graph, but "
                    f"{self.GNN_Model.__class__.__name__} could not process it. "
                    f"graph_index={graph_index}{suffix}."
                ) from exc
            raise

    def _fidelity_probability(self, explanations, original):
        per_class = {c: [] for c in explanations}
        per_pair = {}

        for i, graph in enumerate(self.test_data):
            for c in self._classes_for_graph(i, original, explanations):
                pg, em = self._perturb_graph(graph, explanations[c][i])
                pp = self._predict_perturbed(pg, em, i, c)

                score = float(original[i][c]) - float(pp[c].detach().cpu())
                per_class[c].append(score)
                per_pair[(i, c)] = score

        final, means = self._aggregate_classes(per_class)
        vals = list(per_pair.values())
        negative_fraction = (float(sum(v < 0 for v in vals) / len(vals)) if vals else 0.0)
        return {"fidelity_plus": final, "per_class": means, "per_graph_class": per_pair,
                "negative_fraction": negative_fraction, }

    def _fidelity_prediction(self, explanations, original):
        per_class = {c: [] for c in explanations}
        per_pair = {}

        for i, graph in enumerate(self.test_data):
            original_winner = int(torch.argmax(original[i]).item())
            for c in self._classes_for_graph(i, original, explanations):
                pg, em = self._perturb_graph(graph, explanations[c][i])
                pp = self._predict_perturbed(pg, em, i, c)
                perturbed_winner = int(torch.argmax(pp).item())

                score = float(original_winner != perturbed_winner)
                per_class[c].append(score)
                per_pair[(i, c)] = score

        final, means = self._aggregate_classes(per_class)
        return {"fidelity_plus": final, "per_class": means, "per_graph_class": per_pair,}

    @staticmethod
    def _accuracy(labels, probabilities):
        return float(np.mean(np.argmax(probabilities, axis=1) == labels))

    @staticmethod
    def _auc_roc(labels, probabilities):
        if probabilities.shape[1] == 2:
            return float(roc_auc_score(labels, probabilities[:, 1]))
        return float(roc_auc_score(labels, probabilities, multi_class="ovr", average="macro"))

    def _dataset_probabilities(self, graphs, edge_masks):
        rows = []
        for i, graph in enumerate(graphs):
            pred = self._predict_perturbed(graph, edge_masks[i], i)
            rows.append(pred.detach().cpu().numpy())
        return np.asarray(rows)

    def _dataset_metric(self, name, labels, probabilities):
        if name == "accuracy":
            return self._accuracy(labels, probabilities)
        return self._auc_roc(labels, probabilities)

    def _fidelity_dataset_metric(self, explanations, original, metric_name):
        labels = np.asarray([int(g.y.item()) for g in self.test_data])
        original_matrix = np.asarray([p.numpy() for p in original])
        original_metric = self._dataset_metric(metric_name, labels, original_matrix)

        if self.class_scope == "all_classes":
            per_class = {c: [] for c in explanations}
            perturbed_metrics = {}

            for c in sorted(explanations.keys()):
                graphs, edge_masks = [], []
                for i, graph in enumerate(self.test_data):
                    pg, em = self._perturb_graph(graph, explanations[c][i])
                    graphs.append(pg)
                    edge_masks.append(em)

                matrix = self._dataset_probabilities(graphs, edge_masks)
                perturbed_metric = self._dataset_metric(metric_name, labels, matrix)
                score = original_metric - perturbed_metric
                per_class[c].append(score)
                perturbed_metrics[c] = float(perturbed_metric)

            final, means = self._aggregate_classes(per_class)
            return {"fidelity_plus": final, "per_class": means, "original_metric": float(original_metric),
                    "perturbed_metric_per_class": perturbed_metrics, }

        graphs, edge_masks = [], []
        for i, graph in enumerate(self.test_data):
            c = self._classes_for_graph(i, original, explanations)[0]
            pg, em = self._perturb_graph(graph, explanations[c][i])
            graphs.append(pg)
            edge_masks.append(em)

        matrix = self._dataset_probabilities(graphs, edge_masks)
        perturbed_metric = self._dataset_metric(metric_name, labels, matrix)
        return {"fidelity_plus": float(original_metric - perturbed_metric), "original_metric": float(original_metric),
                "perturbed_metric": float(perturbed_metric), }

    def __call__(self, explanations):
        self.GNN_Model.eval()
        original = self._original_predictions()
        if self.fidelity_criterion == "probability":
            return self._fidelity_probability(explanations, original)
        if self.fidelity_criterion == "prediction":
            return self._fidelity_prediction(explanations, original)
        if self.fidelity_criterion in ("accuracy", "auc_roc"):
            return self._fidelity_dataset_metric(explanations, original, self.fidelity_criterion)
        raise ValueError("Unknown fidelity_criterion.")








