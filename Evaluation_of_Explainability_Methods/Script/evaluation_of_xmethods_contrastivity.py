import itertools
import copy
import numpy as np
from sklearn import metrics
from copy import deepcopy






class Contrastivity:
    """
    Contrastivity for class-specific graph explanations.

    explanations[class_index][graph_index] -> explanation tensor/array

    distance_metric:
      - "jaccard": |A XOR B| / |A OR B| (primary; Pope-style)
      - "normalized_hamming": |A XOR B| / |U|

    class_comparison:
      - "all_pairs"
      - "prediction_vs_others"
      - "ground-truth_label_vs_others"

    For binary explanations use normalization="none" and
    importance_threshold=None. No artificial contrast coefficient is used.
    """

    def __init__(self, GNN_Model, test_data, device, explanation_style="Node", explanation_type="binary",
                 normalization="none", importance_threshold=None, distance_metric="jaccard",
                 class_comparison="all_pairs", edge_semantics=None, ):
        self.GNN_Model = GNN_Model
        self.test_data = test_data
        self.device = device
        self.explanation_style = explanation_style
        self.explanation_type = explanation_type
        self.normalization = normalization
        self.importance_threshold = importance_threshold
        self.distance_metric = distance_metric
        self.class_comparison = class_comparison
        self.edge_semantics = edge_semantics
        self._validate_configuration()

    def _validate_configuration(self):
        if self.explanation_style not in ("Node", "Edge", "Node Feature"):
            raise ValueError("Invalid explanation_style.")
        if self.explanation_type not in ("binary", "continuous"):
            raise ValueError("Invalid explanation_type.")
        if self.normalization not in ("none", "minmax"):
            raise ValueError("Invalid normalization.")
        if self.distance_metric not in ("jaccard", "normalized_hamming"):
            raise ValueError("Invalid distance_metric.")
        if self.class_comparison not in ("all_pairs", "prediction_vs_others", "ground-truth_label_vs_others"):
            raise ValueError("Invalid class_comparison.")

        if self.explanation_style == "Edge":
            if self.edge_semantics not in ("directed", "undirected"):
                raise ValueError("Edge explanations require edge_semantics.")
        elif self.edge_semantics is not None:
            raise ValueError("edge_semantics must be None for non-edge explanations.")

        if self.explanation_type == "binary":
            if self.normalization != "none":
                raise ValueError("Binary explanations require normalization='none'.")
            if self.importance_threshold is not None:
                raise ValueError("Binary explanations need no threshold.")
        elif self.importance_threshold is None:
            raise ValueError("Continuous explanations require a threshold.")

    @staticmethod
    def _minmax(scores):
        scores = scores.float()
        if scores.numel() == 0:
            return scores
        lo, hi = scores.min(), scores.max()
        if torch.isclose(lo, hi):
            return torch.zeros_like(scores)
        return (scores - lo) / (hi - lo)

    def _binary_mask(self, explanation):
        scores = torch.as_tensor(explanation)
        if self.explanation_type == "binary":
            return scores.bool()
        scores = scores.float()
        if self.normalization == "minmax":
            scores = self._minmax(scores)
        return scores >= self.importance_threshold

    @staticmethod
    def _undirected_mask(edge_index, mask):
        if mask.numel() != edge_index.size(1):
            raise ValueError("Edge explanation length != edge_index entries.")

        all_pairs, selected = [], set()
        for idx in range(edge_index.size(1)):
            u, v = int(edge_index[0, idx]), int(edge_index[1, idx])
            pair = (min(u, v), max(u, v))
            all_pairs.append(pair)
            if bool(mask[idx]):
                selected.add(pair)

        unique_pairs = sorted(set(all_pairs))
        return torch.tensor([pair in selected for pair in unique_pairs], dtype=torch.bool)

    def _prepare_mask(self, graph, explanation):
        mask = self._binary_mask(explanation).detach().cpu()

        if self.explanation_style == "Node":
            mask = mask.reshape(-1)
            if mask.numel() != graph.num_nodes:
                raise ValueError("Node explanation length != graph.num_nodes.")
            return mask

        if self.explanation_style == "Edge":
            mask = mask.reshape(-1)
            if mask.numel() != graph.edge_index.size(1):
                raise ValueError("Edge explanation length != edge_index entries.")
            if self.edge_semantics == "undirected":
                return self._undirected_mask(graph.edge_index.detach().cpu(), mask)
            return mask

        if mask.shape != graph.x.shape:
            raise ValueError("Node Feature explanation shape != graph.x shape.")
        return mask.reshape(-1)

    def _model_prediction(self, graph):
        graph = copy.deepcopy(graph).to(self.device)
        name = self.GNN_Model.__class__.__name__

        with torch.no_grad():
            if name == "GCN_plus_GAP_Model":
                _, _, _, pred = self.GNN_Model(graph, None)
            elif name == "DGCNN_Model":
                _, _, _, _, _, _, _, _, _, pred = self.GNN_Model(graph, None)
            elif name == "DIFFPOOL_Model":
                _, _, pred = self.GNN_Model(graph, None)
            elif name == "GIN_Model":
                _, _, _, _, _, pred = self.GNN_Model(graph, None)
            else:
                raise ValueError(f"Unsupported GNN model: {name}")

        pred = torch.squeeze(pred)
        return pred.unsqueeze(0) if pred.dim() == 0 else pred

    def _pairs_for_graph(self, graph_index, classes):
        classes = sorted(classes)
        if self.class_comparison == "all_pairs":
            return list(itertools.combinations(classes, 2))

        if self.class_comparison == "ground-truth_label_vs_others":
            reference = int(self.test_data[graph_index].y.item())
        else:
            pred = self._model_prediction(self.test_data[graph_index])
            reference = int(torch.argmax(pred).item())

        if reference not in classes:
            raise ValueError(f"Reference class {reference} has no explanation.")

        return [tuple(sorted((reference, other))) for other in classes if other != reference]

    @staticmethod
    def _jaccard(mask_a, mask_b):
        xor_n = torch.logical_xor(mask_a, mask_b).sum().item()
        union_n = torch.logical_or(mask_a, mask_b).sum().item()
        if union_n == 0:
            return 0.0, True
        return float(xor_n / union_n), False

    @staticmethod
    def _normalized_hamming(mask_a, mask_b):
        n = mask_a.numel()
        if n == 0:
            return 0.0, True
        diff = torch.logical_xor(mask_a, mask_b).sum().item()
        return float(diff / n), False

    def _distance(self, mask_a, mask_b):
        if mask_a.shape != mask_b.shape:
            raise ValueError("Compared explanation masks have different shapes.")
        if self.distance_metric == "jaccard":
            return self._jaccard(mask_a, mask_b)
        return self._normalized_hamming(mask_a, mask_b)

    def __call__(self, explanations):
        classes = sorted(explanations.keys())
        if len(classes) < 2:
            raise ValueError("Contrastivity requires at least two classes.")

        n_graphs = len(self.test_data)
        for c in classes:
            if len(explanations[c]) != n_graphs:
                raise ValueError(f"Class {c} has {len(explanations[c])} explanations; " f"expected {n_graphs}.")

        if self.class_comparison == "prediction_vs_others":
            self.GNN_Model.eval()

        per_pair_lists = {}
        per_graph_pair = {}
        per_graph = {}
        empty_count = 0
        total_count = 0

        for i, graph in enumerate(self.test_data):
            pairs = self._pairs_for_graph(i, classes)
            needed = sorted({c for pair in pairs for c in pair})
            masks = {c: self._prepare_mask(graph, explanations[c][i]) for c in needed}

            graph_scores = []
            for a, b in pairs:
                score, empty = self._distance(masks[a], masks[b])
                pair = (a, b)
                per_pair_lists.setdefault(pair, []).append(score)
                per_graph_pair[(i, a, b)] = score
                graph_scores.append(score)
                total_count += 1
                empty_count += int(empty)

            per_graph[i] = float(np.mean(graph_scores)) if graph_scores else 0.0

        per_class_pair = {pair: float(np.mean(values)) for pair, values in per_pair_lists.items() if values}
        if not per_class_pair:
            raise ValueError("No valid Contrastivity scores were produced.")

        overall = float(np.mean(list(per_class_pair.values())))

        return {"contrastivity": overall, "per_class_pair": per_class_pair, "per_graph": per_graph,
                "per_graph_class_pair": per_graph_pair,
                "empty_pair_fraction": (float(empty_count / total_count) if total_count else 0.0),
                "distance_metric": self.distance_metric, "class_comparison": self.class_comparison, }














