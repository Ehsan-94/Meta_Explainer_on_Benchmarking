class Stability:
    """Prediction-preserving stability for class-specific GNN explanations."""

    def __init__(self, GNN_Model, test_data, device, explainer_fn, explanation_style="Node", explanation_type="binary",
                 normalization="none", importance_threshold=None, class_scope="all_classes",
                 stability_measure="explanation_distance", explanation_distance="cosine",
                 perturbation_aggregation="mean", perturbation_mode="feature", feature_perturbation="auto",
                 feature_strength=0.05, structural_perturbation="edge_rewire", structural_rate=0.05,
                 prediction_constraint="same_class", prediction_distance="l2", delta=0.1, num_valid_perturbations=10,
                 max_attempts=100, edge_semantics=None, random_seed=42, ):
        self.GNN_Model, self.test_data, self.device = GNN_Model, test_data, device
        self.explainer_fn = explainer_fn
        self.explanation_style, self.explanation_type = explanation_style, explanation_type
        self.normalization, self.importance_threshold = normalization, importance_threshold
        self.class_scope, self.stability_measure = class_scope, stability_measure
        self.explanation_distance = explanation_distance
        self.perturbation_aggregation = perturbation_aggregation
        self.perturbation_mode = perturbation_mode
        self.feature_perturbation, self.feature_strength = feature_perturbation, feature_strength
        self.structural_perturbation, self.structural_rate = structural_perturbation, structural_rate
        self.prediction_constraint, self.prediction_distance = prediction_constraint, prediction_distance
        self.delta = delta
        self.num_valid_perturbations, self.max_attempts = num_valid_perturbations, max_attempts
        self.edge_semantics, self.random_seed = edge_semantics, random_seed
        self._validate()
        random.seed(random_seed); np.random.seed(random_seed); torch.manual_seed(random_seed)
        self.feature_diagnostics = self.detect_feature_representation()

    def _validate(self):
        allowed = {
            "explanation_style": (self.explanation_style, {"Node","Edge","Node Feature"}),
            "explanation_type": (self.explanation_type, {"binary","continuous"}),
            "normalization": (self.normalization, {"none","minmax"}),
            "class_scope": (self.class_scope, {"all_classes","prediction","ground-truth label"}),
            "stability_measure": (self.stability_measure, {"explanation_distance","ground_truth_auc"}),
            "explanation_distance": (self.explanation_distance, {"cosine","jaccard","normalized_hamming"}),
            "perturbation_aggregation": (self.perturbation_aggregation, {"mean","max"}),
            "perturbation_mode": (self.perturbation_mode, {"feature","structure","both"}),
            "feature_perturbation": (self.feature_perturbation, {"auto","gaussian","mask","flip","categorical_swap"}),
            "structural_perturbation": (self.structural_perturbation, {"edge_rewire","edge_delete","edge_add"}),
            "prediction_constraint": (self.prediction_constraint, {"same_class","probability_distance","both"}),
        }
        for name, (value, choices) in allowed.items():
            if value not in choices: raise ValueError(f"Invalid {name}: {value}")
        if self.prediction_distance not in {"l1","l2"}: raise ValueError("prediction_distance must be l1/l2.")
        if self.num_valid_perturbations < 1 or self.max_attempts < self.num_valid_perturbations:
            raise ValueError("Require max_attempts >= num_valid_perturbations >= 1.")
        if self.explanation_style == "Edge" and self.edge_semantics not in {"directed","undirected"}:
            raise ValueError("Edge explanations require edge_semantics.")
        if self.explanation_style != "Edge" and self.edge_semantics is not None:
            raise ValueError("edge_semantics must be None for non-edge explanations.")
        if self.explanation_type == "binary" and (self.normalization != "none" or self.importance_threshold is not None):
            raise ValueError("Binary explanations require normalization='none' and no threshold.")
        if self.explanation_type == "continuous" and self.importance_threshold is None:
            raise ValueError("Continuous explanations require importance_threshold.")
        if self.explanation_style == "Edge" and self.perturbation_mode in {"structure","both"} and self.stability_measure == "explanation_distance":
            raise ValueError("Structural perturbation changes the edge universe; direct Edge-mask comparison needs explicit correspondence.")

    def detect_feature_representation(self):
        xs = [g.x.detach().cpu().float() for g in self.test_data if getattr(g,"x",None) is not None and g.x.numel()]
        if not xs: return {"feature_type":"missing","recommended_perturbation":None}
        x = torch.cat(xs, 0)
        binary = torch.isclose(x, torch.zeros_like(x), atol=1e-6) | torch.isclose(x, torch.ones_like(x), atol=1e-6)
        bf = float(binary.float().mean())
        oh = binary.all(1) & torch.isclose(x.sum(1), torch.ones(x.size(0)), atol=1e-6)
        of = float(oh.float().mean())
        std = x.std(0, unbiased=False) if x.size(0)>1 else torch.zeros(x.size(1))
        cf = float((std <= 1e-12).float().mean())
        if cf == 1.0: ft, rec = "constant", None
        elif bf >= .99 and of >= .99: ft, rec = "categorical_onehot", "categorical_swap"
        elif bf >= .99: ft, rec = "binary", "flip"
        else: ft, rec = "continuous", "gaussian"
        return {"feature_type":ft,"num_features":int(x.size(1)),"binary_fraction":bf,
                "onehot_row_fraction":of,"constant_feature_fraction":cf,"recommended_perturbation":rec}

    def _feature_method(self):
        if self.feature_perturbation != "auto": return self.feature_perturbation
        m = self.feature_diagnostics.get("recommended_perturbation")
        if m is None: raise ValueError("auto cannot choose a meaningful feature perturbation; override it or use structure.")
        return m

    def _model_probs(self, graph):
        g = copy.deepcopy(graph).to(self.device); name = self.GNN_Model.__class__.__name__
        with torch.no_grad():
            if name=="GCN_plus_GAP_Model": *_, out = self.GNN_Model(g,None)
            elif name=="DGCNN_Model": *_, out = self.GNN_Model(g,None)
            elif name=="DIFFPOOL_Model": *_, out = self.GNN_Model(g,None)
            elif name=="GIN_Model": *_, out = self.GNN_Model(g,None)
            else: raise ValueError(f"Unsupported GNN model: {name}")
        out = torch.squeeze(out)
        if out.dim()==0: out=out.unsqueeze(0)
        if torch.all(out>=0) and torch.isclose(out.sum(), torch.tensor(1.,device=out.device), atol=1e-4): p=out
        else: p=torch.softmax(out,-1)
        return p.detach().cpu()

    def _accepted(self, p, q):
        same = int(p.argmax()) == int(q.argmax())
        d = torch.dist(p,q,p=1 if self.prediction_distance=="l1" else 2).item() <= self.delta
        return same if self.prediction_constraint=="same_class" else d if self.prediction_constraint=="probability_distance" else same and d

    def _feature_perturb(self, graph):
        g=copy.deepcopy(graph); x=g.x.clone(); method=self._feature_method()
        if method=="gaussian":
            allx=torch.cat([z.x.detach().cpu().float() for z in self.test_data],0)
            std=allx.std(0,unbiased=False).to(x.device); std=torch.where(std>1e-12,std,torch.ones_like(std))
            g.x=x.float()+torch.randn_like(x.float())*(self.feature_strength*std); return g
        rate=float(np.clip(self.feature_strength,0,1))
        if method in {"mask","flip"}:
            flat=x.reshape(-1).clone(); k=max(1,round(rate*flat.numel())) if rate>0 else 0
            if k:
                idx=torch.randperm(flat.numel(),device=flat.device)[:k]
                flat[idx]=0 if method=="mask" else 1-flat[idx]
            g.x=flat.reshape_as(x); return g
        if method=="categorical_swap":
            k=max(1,round(rate*x.size(0))) if rate>0 else 0; y=x.clone()
            for node in torch.randperm(x.size(0))[:k].tolist():
                cur=int(y[node].argmax()); choices=[j for j in range(x.size(1)) if j!=cur]
                if choices: y[node].zero_(); y[node,random.choice(choices)]=1
            g.x=y; return g
        raise ValueError(method)

    @staticmethod
    def _pairs(edge_index, undirected):
        s=set()
        for i in range(edge_index.size(1)):
            u,v=int(edge_index[0,i]),int(edge_index[1,i]); s.add((min(u,v),max(u,v)) if undirected else (u,v))
        return sorted(s)

    @staticmethod
    def _edge_index(pairs, undirected, device):
        e=[]
        for u,v in pairs:
            e.append((u,v))
            if undirected and u!=v: e.append((v,u))
        return torch.tensor(e,dtype=torch.long,device=device).t().contiguous() if e else torch.empty((2,0),dtype=torch.long,device=device)

    def _structure_perturb(self, graph):
        g=copy.deepcopy(graph); undirected=self.edge_semantics!="directed"; pairs=self._pairs(g.edge_index,undirected)
        n=int(g.num_nodes); k=max(1,round(self.structural_rate*max(len(pairs),1))) if self.structural_rate>0 else 0
        if n<2 or k==0:return g
        current=set(pairs)
        candidates=[(u,v) for u in range(n) for v in range(u+1 if undirected else 0,n)
                    if u!=v and ((min(u,v),max(u,v)) if undirected else (u,v)) not in current]
        if self.structural_perturbation=="edge_delete":
            rem=set(random.sample(pairs,min(k,len(pairs)))) if pairs else set(); new=current-rem
        elif self.structural_perturbation=="edge_add":
            add=set(random.sample(candidates,min(k,len(candidates)))) if candidates else set(); new=current|add
        else:
            rem=set(random.sample(pairs,min(k,len(pairs)))) if pairs else set(); retained=current-rem
            cand=[p for p in candidates if p not in retained]; add=set(random.sample(cand,min(k,len(cand)))) if cand else set(); new=retained|add
        g.edge_index=self._edge_index(sorted(new),undirected,g.edge_index.device); return g

    def _perturb(self,g):
        q=copy.deepcopy(g)
        if self.perturbation_mode in {"feature","both"}: q=self._feature_perturb(q)
        if self.perturbation_mode in {"structure","both"}: q=self._structure_perturb(q)
        return q

    def _mask(self, graph, explanation):
        s=torch.as_tensor(explanation)
        if self.explanation_type=="continuous":
            s=s.float()
            if self.normalization=="minmax":
                lo,hi=s.min(),s.max(); s=(s-lo)/(hi-lo) if not torch.isclose(lo,hi) else torch.zeros_like(s)
            s=s>=self.importance_threshold
        else:s=s.bool()
        s=s.detach().cpu()
        if self.explanation_style=="Node":
            s=s.reshape(-1)
            if s.numel()!=graph.num_nodes: raise ValueError("Node explanation length mismatch.")
        elif self.explanation_style=="Node Feature":
            if s.shape!=graph.x.shape: raise ValueError("Node Feature explanation shape mismatch.")
            s=s.reshape(-1)
        else:
            s=s.reshape(-1)
            if s.numel()!=graph.edge_index.size(1): raise ValueError("Edge explanation length mismatch.")
            if self.edge_semantics=="undirected":
                pairs=self._pairs(graph.edge_index.detach().cpu(),True); selected=set()
                for i in range(graph.edge_index.size(1)):
                    if bool(s[i]):
                        u,v=int(graph.edge_index[0,i]),int(graph.edge_index[1,i]); selected.add((min(u,v),max(u,v)))
                s=torch.tensor([p in selected for p in pairs],dtype=torch.bool)
        return s

    def _distance(self,a,b):
        if a.shape!=b.shape: raise ValueError("Explanation masks have different shapes.")
        if self.explanation_distance=="cosine":
            af,bf=a.float(),b.float()
            if not af.any() and not bf.any(): return 0.
            if not af.any() or not bf.any(): return 1.
            return float(1-F.cosine_similarity(af[None],bf[None]).item())
        xor=torch.logical_xor(a,b).sum().item()
        if self.explanation_distance=="jaccard":
            union=torch.logical_or(a,b).sum().item(); return 0. if union==0 else xor/union
        return 0. if a.numel()==0 else xor/a.numel()

    @staticmethod
    def _auc(y,s):
        y=np.asarray(y).astype(int).ravel(); s=np.asarray(s,float).ravel()
        pos=y==1; neg=y==0
        if pos.sum()==0 or neg.sum()==0:return None
        order=np.argsort(s,kind="mergesort"); ranks=np.empty(len(s),float); ranks[order]=np.arange(1,len(s)+1)
        for val in np.unique(s):
            ids=np.where(s==val)[0]
            if len(ids)>1:ranks[ids]=ranks[ids].mean()
        return float((ranks[pos].sum()-pos.sum()*(pos.sum()+1)/2)/(pos.sum()*neg.sum()))

    def __call__(self, explanations, ground_truth_explanations=None, perturbed_ground_truth_fn=None):
        classes=sorted(explanations); self.GNN_Model.eval()
        per_class={c:[] for c in classes}; per_gc={}; valid={}; attempts_d={}; insufficient=0; total_gc=0
        for i,g in enumerate(self.test_data):
            p=self._model_probs(g)
            selected=classes if self.class_scope=="all_classes" else [int(p.argmax()) if self.class_scope=="prediction" else int(g.y.item())]
            for c in selected:
                total_gc+=1; original=explanations[c][i]
                if self.stability_measure=="explanation_distance": base=self._mask(g,original)
                else:
                    if ground_truth_explanations is None:
                        raise ValueError("ground_truth_auc requires ground truth.")
                    gt=ground_truth_explanations[c][i] if isinstance(ground_truth_explanations,dict) else ground_truth_explanations[i]
                    base_auc=self._auc(gt,original)
                    if base_auc is None:
                        per_gc[(i,c)]=None; insufficient+=1; continue
                ds=[]; att=0
                while len(ds)<self.num_valid_perturbations and att<self.max_attempts:
                    att+=1; q=self._perturb(g); qp=self._model_probs(q)
                    if not self._accepted(p,qp):continue
                    qe=self.explainer_fn(copy.deepcopy(q),c)
                    if self.stability_measure=="explanation_distance": d=self._distance(base,self._mask(q,qe))
                    else:
                        qgt=gt if perturbed_ground_truth_fn is None else perturbed_ground_truth_fn(g,q,gt,c)
                        qa=self._auc(qgt,qe)
                        if qa is None:continue
                        d=base_auc-qa
                    ds.append(float(d))
                valid[(i,c)]=len(ds); attempts_d[(i,c)]=att
                if len(ds)<self.num_valid_perturbations:insufficient+=1
                if not ds:per_gc[(i,c)]=None; continue
                score=float(np.mean(ds) if self.perturbation_aggregation=="mean" else np.max(ds))
                per_gc[(i,c)]=score; per_class[c].append(score)
        pc={c:float(np.mean(v)) for c,v in per_class.items() if v}
        if not pc:raise ValueError("No valid Stability observations.")
        instability=float(np.mean(list(pc.values())))
        return {"instability": instability,
                "stability": 1 - instability if self.stability_measure == "explanation_distance" else None,
                "per_class_instability": pc, "per_graph_class_instability": per_gc, "valid_perturbation_counts": valid,
                "attempt_counts": attempts_d,
                "valid_perturbation_fraction": sum(valid.values()) / sum(attempts_d.values()) if sum(
                    attempts_d.values()) else 0.,
                "insufficient_graph_class_fraction": insufficient / total_gc if total_gc else 0.,
                "feature_diagnostics": self.feature_diagnostics,
                "resolved_feature_perturbation": self._feature_method() if self.perturbation_mode in {"feature",
                                                                                                      "both"} else None,
                "stability_measure": self.stability_measure,
                "explanation_distance": self.explanation_distance if self.stability_measure == "explanation_distance" else None,
                "perturbation_aggregation": self.perturbation_aggregation,
                "prediction_constraint": self.prediction_constraint, }
















